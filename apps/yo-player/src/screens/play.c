#define DESCRIPTION_MARGIN_X    120
#define DESCRIPTION_MARGIN_Y    80
#define DESCRIPTION_TEXT_SIZE   24
#define DESCRIPTION_SCROLL_STEP 40

// the video to play, set by playVideo() before the screen is pushed. defaults to
